const isObj = (v) => v && typeof v === 'object' && !Array.isArray(v)

/** Deep-merge `extra` into `base` in place (extra wins on leaf conflicts). */
export function mergeTranslations(base, extra) {
  for (const [k, v] of Object.entries(extra)) {
    if (isObj(v) && isObj(base[k])) mergeTranslations(base[k], v)
    else base[k] = v
  }
  return base
}
